    for d in USE_PAGES_DATA:
        body = f"<p class=\"lead\">{d['lead']}</p>"
        for h2, html in d["sections"]:
            body += f"<section><h2>{h2}</h2>{html}</section>"
        body += _checklist(CHECKLIST_BASE)
        body += (
            "<section><h2>관련 안내</h2>"
            + _links([
                ("이용 장소별 안내 전체", "/use/"),
                ("예약 전 확인사항", "/check/"),
                ("예약 안내", "/reservation/"),
            ])
            + "</section>"
            + "<section><h2>운영 기준</h2>" + OPERATION_NOTE + "</section>"
        )
        pages.append({
            "path": f"use/{d['slug']}/",
            "title": d["title"],
            "desc": d["desc"],
            "h1": d["h1"],
            "breadcrumb": [("이용 장소별", "/use/"), (d["name"], None)],
            "body": body,
            "faq": d.get("faq", []),
        })
    return pages
